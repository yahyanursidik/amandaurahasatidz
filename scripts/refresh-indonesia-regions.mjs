/** Explicit refresh of bundled BPS snapshot; never runs at build or browser runtime. */
import { writeFile } from "node:fs/promises";
const base = "https://sig.bps.go.id";
const period = "2025_2.2025";
async function get(level, parent) {
  const url = new URL("/rest-drop-down/getwilayah", base);
  url.search = new URLSearchParams({ level, parent, periode_merge: period });
  const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
  if (!response.ok) throw new Error(`BPS returned ${response.status}`);
  const rows = await response.json();
  if (!Array.isArray(rows) || !rows.length) throw new Error(`Missing region data: ${parent}`);
  return rows;
}
const provinces = await get("provinsi", period);
const records = [];
for (let offset = 0; offset < provinces.length; offset += 4) {
  const batches = await Promise.all(provinces.slice(offset, offset + 4).map(async (province) => {
    const cities = await get("kabupaten", province.kode);
    return cities.map((city) => ({ id: city.kode, provinceId: province.kode,
      city: `${Number(city.kode.slice(2)) >= 71 ? "KOTA" : "KABUPATEN"} ${city.nama}`, province: province.nama }));
  }));
  records.push(...batches.flat());
}
records.sort((a, b) => a.id.localeCompare(b.id));
if (provinces.length !== 38 || records.length !== 514 || new Set(records.map((r) => r.id)).size !== 514 ||
  records.some((r) => !/^\d{4}$/.test(r.id) || !r.id.startsWith(r.provinceId))) throw new Error("Unexpected BPS snapshot; review before updating.");
const output = `/** BPS SIG wilayah snapshot, period ${period}. Generated by scripts/refresh-indonesia-regions.mjs.
 * Source: ${base}/rest-drop-down/getwilayah. Codes use BPS, not Kemendagri namespace.
 * Local snapshot shared between server validation and client; no third-party browser requests.
 */
export type Regency = { id: string; provinceId: string; city: string; province: string };
export const INDONESIA_REGENCIES: Regency[] = ${JSON.stringify(records, null, 2)};
const regionIndex = new Map(INDONESIA_REGENCIES.map((region) => [region.id, region]));
export function findIndonesianRegency(code: string): Regency | undefined {
  return regionIndex.get(code);
}
`;
await writeFile(new URL("../src/lib/indonesiaRegionData.ts", import.meta.url), output);
console.log(JSON.stringify({ provinces: provinces.length, regencies: records.length, period }));